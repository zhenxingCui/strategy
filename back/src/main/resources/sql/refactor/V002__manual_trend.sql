-- Manual trend values are kept separate from automatically calculated facts.
CREATE TABLE sr_manual_trend (
    id BIGINT NOT NULL AUTO_INCREMENT,
    legacy_table VARCHAR(64) NOT NULL,
    legacy_id BIGINT NOT NULL,
    scope_type VARCHAR(16) NOT NULL,
    strategy_class VARCHAR(16) NOT NULL,
    strategy_code VARCHAR(64) DEFAULT NULL,
    strategy_ref BIGINT DEFAULT NULL,
    stat_month DATE NOT NULL,
    customer_group VARCHAR(64) DEFAULT NULL,
    channel VARCHAR(64) NOT NULL,
    big_category VARCHAR(128) DEFAULT NULL,
    small_category VARCHAR(128) DEFAULT NULL,
    city_id VARCHAR(64) NOT NULL,
    county_id VARCHAR(64) NOT NULL,
    metric_code VARCHAR(64) NOT NULL,
    metric_value DECIMAL(20,4) DEFAULT NULL,
    manual_qoq DECIMAL(14,4) DEFAULT NULL,
    qoq_unit VARCHAR(8) NOT NULL,
    scope_hash CHAR(64) NOT NULL,
    status TINYINT NOT NULL,
    source_batch VARCHAR(64) DEFAULT NULL,
    remark VARCHAR(500) DEFAULT NULL,
    created_by VARCHAR(64) DEFAULT NULL,
    updated_by VARCHAR(64) DEFAULT NULL,
    create_time DATETIME NOT NULL,
    update_time DATETIME NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_manual_trend_legacy (legacy_table, legacy_id),
    KEY idx_manual_trend_lookup (strategy_class, scope_type, metric_code, stat_month, status),
    KEY idx_manual_trend_strategy (strategy_ref, stat_month, metric_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
